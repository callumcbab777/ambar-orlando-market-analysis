#!/usr/bin/env python3
"""Rebuild the 'Residences · The week ahead' data.

The browser computes the residence cards LIVE from data/comps.json with
assets/js/week-ahead-engine.js (a port of week_ahead/engine.py), for whichever week is
selected, and for the selected NIGHT (each hotel's rate for that one night; the page defaults to
today in America/New_York). This script writes data/week_ahead.json + data/week_ahead.js containing:
  * the assumptions and floor-plan data the browser engine needs, and
  * reference outputs from the Python engine for every collected week and every collected
    night (nights go to data/week_ahead_nights.json; used by the parity test and for
    auditing; the page never displays these).

    python3 update_week_ahead.py            # rebuild (runs automatically from update_data.py)
    python3 update_week_ahead.py --check    # exit 1 if the committed files are out of date
    python3 update_week_ahead.py --week 2026-10-12   # print one week's summary
    python3 update_week_ahead.py --night 2026-10-22  # print one night's summary

Future per-unit-type STR feed (see README; written to data/week_ahead_feed.json, not rendered yet):
    python3 update_week_ahead.py --feed data/week_ahead/comps_feed.csv --as-of 2026-10-26 [--live]
"""
import argparse
import json
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))
from week_ahead import engine  # noqa: E402

DATA = ROOT / "data"
WA = DATA / "week_ahead"


def load_inputs():
    return engine.load_json(WA / "assumptions.json"), engine.load_json(WA / "units.json"), engine.load_json(DATA / "comps.json")


def build():
    cfg, units_doc, db = load_inputs()
    weeks = engine.run_all_weeks(db, cfg, units_doc["units"])
    nights = engine.run_all_nights(db, cfg, units_doc["units"])
    ok = [w for w, o in weeks.items() if "error" not in o]
    return {
        "_note": "Generated by update_week_ahead.py. The page recomputes every figure live from data/comps.json "
                 "with assets/js/week-ahead-engine.js; 'reference_outputs' are the Python engine's weekly results for parity checks only (nightly results: data/week_ahead_nights.json).",
        "source": "data/comps.json",
        "comps_last_updated": db["meta"].get("last_updated"),
        "latest_week": ok[-1] if ok else None,
        "assumptions": cfg,
        "residences": units_doc,
        "reference_outputs": weeks,
    }, {
        "_note": "Generated by update_week_ahead.py. The Python engine's nightly results (run_all_nights) for every collected night, "
                 "for the JS parity test and auditing. The page computes the selected night live and never loads this file.",
        "source": "data/comps.json",
        "comps_last_updated": db["meta"].get("last_updated"),
        "reference_nights": nights,
    }


def render(res):
    return (json.dumps(res, indent=1, ensure_ascii=False),
            "/* Generated by update_week_ahead.py — do not edit by hand. */\nwindow.WEEK_AHEAD_DATA = "
            + json.dumps(res, ensure_ascii=False) + ";\n")


def summary(o):
    label = f"night of {o['night']}" if "night" in o else f"week of {o['week_start']}"
    if "error" in o:
        print(f"{label}: {o['error']}")
        return
    b = o["baseline"]
    print(f"{label} · comp {b['method']} ${b['median']:.2f} (P25–P75 ${b['p25']:.2f}–${b['p75']:.2f}) "
          f"· {b['comp_count']} hotels ({b['trimmed_out']} trimmed) · mean ${b['diag_mean']:.2f}, gap {b['gap_pct']:.1f}%"
          f"{' FLAGGED' if b['flagged'] else ''} · {b['confidence']}")
    for c in o["comps"]:
        if "night" in o:
            print(f"   {c['status']:<40.40s} {c['name']:<48s} rate {c['rate']}")
        else:
            print(f"   {c['status']:<40.40s} {c['name']:<48s} nights {c['priced_nights']}/{c['nights']}  median {c['weekly_median']}")
    for u in o["units"]:
        print(f"  {u['id']}: ADR {u['adr']:.2f} ({u['adr_p25']:.2f}–{u['adr_p75']:.2f}) occ {u['occupancy']:.1%} "
              f"RevPAU {u['revpau']:.2f} ({u['revpau_p25']:.2f}–{u['revpau_p75']:.2f}) {u['confidence']} "
              f"· vs base ADR {u['vs_base_adr_pct']:+.1f}% RevPAU {u['vs_base_revpau_pct']:+.1f}%")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--week", help="print the summary for this week start (YYYY-MM-DD)")
    ap.add_argument("--night", help="print the summary for this night (YYYY-MM-DD)")
    ap.add_argument("--check", action="store_true", help="exit 1 if the committed output is out of date")
    ap.add_argument("--feed", help="per-unit-type comp feed (.csv/.json) -> data/week_ahead_feed.json")
    ap.add_argument("--as-of")
    ap.add_argument("--live", action="store_true")
    ap.add_argument("-q", "--quiet", action="store_true")
    a = ap.parse_args(argv)
    if a.feed:
        cfg, units_doc, _ = load_inputs()
        comps = engine.load_feed(a.feed)
        d = date.fromisoformat(a.as_of) if a.as_of else max(c.date for c in comps)
        res = engine.run(comps, cfg, units_doc["units"], d, data_status="live" if a.live else "sample")
        (DATA / "week_ahead_feed.json").write_text(json.dumps(res, indent=1, ensure_ascii=False), encoding="utf-8")
        print("wrote data/week_ahead_feed.json")
        return
    res, nres = build()
    j, js = render(res)
    jn = json.dumps(nres, indent=1, ensure_ascii=False)
    pj, pjs, pjn = DATA / "week_ahead.json", DATA / "week_ahead.js", DATA / "week_ahead_nights.json"
    if a.check:
        ok = all(f.exists() for f in (pj, pjs, pjn)) and pj.read_text(encoding="utf-8") == j and pjs.read_text(encoding="utf-8") == js \
            and pjn.read_text(encoding="utf-8") == jn
        print("week_ahead data is up to date" if ok else "week_ahead data is OUT OF DATE: run python3 update_week_ahead.py")
        sys.exit(0 if ok else 1)
    pj.write_text(j, encoding="utf-8")
    pjs.write_text(js, encoding="utf-8")
    pjn.write_text(jn, encoding="utf-8")
    if not a.quiet:
        if a.night:
            summary(nres["reference_nights"].get(a.night) or {"night": a.night, "error": "no rates collected for this night"})
        else:
            summary(res["reference_outputs"][a.week or res["latest_week"]])


if __name__ == "__main__":
    main()
