#!/usr/bin/env python3
"""Rebuild the 'Residences · The week ahead' data.

Default (live) mode — runs automatically at the end of update_data.py and in the
GitHub Action whenever data/comps.json changes:
    python3 update_week_ahead.py                 # latest collected week in data/comps.json
    python3 update_week_ahead.py --week 2026-10-12
    python3 update_week_ahead.py --check         # exit 1 if data/week_ahead.json is out of date

Future per-unit-type STR feed (CSV/JSON, see README):
    python3 update_week_ahead.py --feed data/week_ahead/comps_feed.csv --as-of 2026-10-26 [--live]

Writes data/week_ahead.json and data/week_ahead.js (file:// mirror). Do not edit those by hand.
"""
import argparse
import json
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))
from week_ahead import engine  # noqa: E402

DATA = ROOT / "data"
WA = DATA / "week_ahead"


def build(feed=None, as_of=None, live=False, week=None):
    cfg = engine.load_json(WA / "assumptions.json")
    units_doc = engine.load_json(WA / "units.json")
    if feed:
        comps = engine.load_feed(feed)
        if not comps:
            sys.exit("feed is empty")
        d = date.fromisoformat(as_of) if as_of else max(c.date for c in comps)
        res = engine.run(comps, cfg, units_doc["units"], d, data_status="live" if live else "sample")
        res["mode"] = "unit_type_feed"
        res["feed_file"] = Path(feed).name
    else:
        db = engine.load_json(DATA / "comps.json")
        res = engine.run_hotel_median(db, cfg, units_doc["units"], week)
        res["feed_file"] = "data/comps.json"
        res["comps_last_updated"] = db["meta"].get("last_updated")
    res["assumptions"] = {
        "unit_types": {k: {kk: v.get(kk) for kk in ("label", "plural", "realization", "position_index", "realization_status", "position_index_status")}
                       for k, v in cfg["unit_types"].items()},
        "layouts": cfg["layouts"], "gap_fill": {k: v for k, v in cfg["gap_fill"].items() if not k.startswith("_")},
        "pipeline": {k: v for k, v in cfg["pipeline"].items() if not k.startswith("_")},
        "hotel_median": {k: v for k, v in cfg.get("hotel_median", {}).items() if not k.startswith("_")},
        "occupancy_model": {k: v for k, v in cfg["occupancy_model"].items() if not k.startswith("_")},
    }
    res["residences"] = units_doc
    return res


def render(res):
    j = json.dumps(res, indent=1, ensure_ascii=False)
    js = ("/* Generated by update_week_ahead.py — do not edit by hand. */\nwindow.WEEK_AHEAD_DATA = "
          + json.dumps(res, ensure_ascii=False) + ";\n")
    return j, js


def summary(res):
    if res.get("mode") == "hotel_median":
        b = res["baseline"]
        print(f"week of {res['week_start']} · comp {b['method']} ${b['median']:.2f} (P25–P75 ${b['p25']:.2f}–${b['p75']:.2f}) "
              f"· {b['comp_count']} hotels ({b['trimmed_out']} trimmed) · mean ${b['diag_mean']:.2f}, gap {b['gap_pct']:.1f}%"
              f"{' FLAGGED' if b['flagged'] else ''} · {b['confidence']}")
        for c in res["comps"]:
            print(f"   {c['status']:<10.40s} {c['name']:<48s} nights {c['priced_nights']}/{c['nights']}  median {c['weekly_median']}")
    for u in res["units"]:
        extra = f" vs doc {u['vs_doc_base_pct']:+.1f}%" if "vs_doc_base_pct" in u else ""
        print(f"  {u['id']}: ADR {u['adr']:.2f} ({u['adr_p25']:.2f}–{u['adr_p75']:.2f}) occ {u['occupancy']:.1%} (doc {u.get('doc_occupancy',0):.0%}) "
              f"RevPAU {u['revpau']:.2f} {u['confidence']}{extra}")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--feed", help="per-unit-type comp feed (.csv or .json); omit to use data/comps.json")
    ap.add_argument("--as-of", help="YYYY-MM-DD (feed mode)")
    ap.add_argument("--live", action="store_true", help="feed mode: mark output as live")
    ap.add_argument("--week", help="hotel mode: week start YYYY-MM-DD (default latest collected)")
    ap.add_argument("--check", action="store_true", help="exit 1 if the committed output is out of date")
    ap.add_argument("-q", "--quiet", action="store_true")
    a = ap.parse_args(argv)
    res = build(a.feed, a.as_of, a.live, a.week)
    j, js = render(res)
    pj, pjs = DATA / "week_ahead.json", DATA / "week_ahead.js"
    if a.check:
        ok = pj.exists() and pjs.exists() and pj.read_text(encoding="utf-8") == j and pjs.read_text(encoding="utf-8") == js
        print("week_ahead data is up to date" if ok else "week_ahead data is OUT OF DATE: run python3 update_week_ahead.py")
        sys.exit(0 if ok else 1)
    pj.write_text(j, encoding="utf-8")
    pjs.write_text(js, encoding="utf-8")
    if not a.quiet:
        summary(res)


if __name__ == "__main__":
    main()
