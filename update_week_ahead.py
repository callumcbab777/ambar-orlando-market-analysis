#!/usr/bin/env python3
"""Rebuild the 'Week ahead by residence' section data.

  python3 update_week_ahead.py                                  # sample feed, as_of = latest record date
  python3 update_week_ahead.py --feed data/week_ahead/comps_feed.csv --as-of 2026-10-26 --live

Reads   data/week_ahead/<feed>.csv|.json, assumptions.json, units.json
Writes  data/week_ahead.json and data/week_ahead.js (file:// mirror). Do not edit those by hand.
"""
import argparse
import json
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))
from week_ahead import engine  # noqa: E402

WA = ROOT / "data" / "week_ahead"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--feed", default=str(WA / "comps_feed.sample.csv"), help="comp feed (.csv or .json)")
    ap.add_argument("--as-of", help="YYYY-MM-DD; defaults to the latest record date in the feed")
    ap.add_argument("--live", action="store_true", help="mark output as a live feed (removes the SAMPLE badge)")
    a = ap.parse_args(argv)

    comps = engine.load_feed(a.feed)
    if not comps:
        sys.exit("feed is empty")
    as_of = date.fromisoformat(a.as_of) if a.as_of else max(c.date for c in comps)
    cfg = engine.load_json(WA / "assumptions.json")
    units_doc = engine.load_json(WA / "units.json")
    is_sample = not a.live
    res = engine.run(comps, cfg, units_doc["units"], as_of, data_status="sample" if is_sample else "live")
    res["feed_file"] = Path(a.feed).name
    res["assumptions"] = {
        "unit_types": {k: {kk: v[kk] for kk in ("label", "plural", "realization", "position_index")} for k, v in cfg["unit_types"].items()},
        "layouts": cfg["layouts"], "gap_fill": {k: v for k, v in cfg["gap_fill"].items() if not k.startswith("_")},
        "pipeline": {k: v for k, v in cfg["pipeline"].items() if not k.startswith("_")},
    }
    res["residences"] = units_doc
    out = WA.parent / "week_ahead.json"
    out.write_text(json.dumps(res, indent=1, ensure_ascii=False), encoding="utf-8")
    (WA.parent / "week_ahead.js").write_text(
        "/* Generated by update_week_ahead.py — do not edit by hand. */\nwindow.WEEK_AHEAD_DATA = "
        + json.dumps(res, ensure_ascii=False) + ";\n", encoding="utf-8")
    print(f"as_of {res['as_of']} · {res['data_status'].upper()} · records {res['pipeline']}")
    for t, r in res["types"].items():
        print(f"  {t:7s} {r['method']:12s} n={r['comp_count']:2d} conf={r['confidence']:8s} ADR={r['adr']:.2f} "
              f"range {r['adr_p25']:.2f}-{r['adr_p75']:.2f} gap={r['gap_pct']}{' FLAG' if r['flagged'] else ''}")
    for u in res["units"]:
        print(f"  {u['id']}: ADR {u['adr']:.2f} occ {u['occupancy']:.0%} RevPAU {u['revpau']:.2f}")


if __name__ == "__main__":
    main()
